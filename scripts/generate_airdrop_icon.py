"""Generate the 32px AirDrop list icon; no third-party dependencies required."""

import math
from pathlib import Path


def ink(x, y):
    dx, dy = x - 16, y - 14
    radius = math.hypot(dx, dy)
    # Leave the bottom sector open for the upward-pointing sharing arrow.
    rings = (dy <= 0 or abs(dx) > dy * 0.72) and any(
        abs(radius - r) <= 1 for r in (4, 8, 12)
    )
    triangle = 17 <= y <= 29 and abs(dx) <= (y - 17) * 0.58
    return rings or triangle


def main():
    data = []
    ink_rows = []
    for y in range(32):
        for block in range(4):
            byte = 0
            for bit in range(8):
                x = block * 8 + bit
                coverage = sum(
                    ink(x + (sx + 0.5) / 4, y + (sy + 0.5) / 4)
                    for sy in range(4) for sx in range(4)
                )
                black = coverage >= 8
                byte = (byte << 1) | int(not black)
                if black:
                    ink_rows.append(y)
            data.append(byte)
    center = round(sum(ink_rows) / len(ink_rows))
    lines = ['#pragma once', '', '#include "Icon.h"', '',
             '// Generated by scripts/generate_airdrop_icon.py. Do not edit.',
             'static constexpr uint8_t icon_airdrop_32_bits[] = {']
    for start in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{v:02X}' for v in data[start:start + 16]) + ',')
    lines.extend(['};', f'static constexpr freeink::Icon icon_airdrop_32 = '
                  f'{{32, 32, {center}, icon_airdrop_32_bits}};', ''])
    output = Path(__file__).resolve().parents[1] / 'src/components/icons/airdrop.h'
    output.write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
