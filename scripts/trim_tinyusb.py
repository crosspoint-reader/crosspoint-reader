"""Link a trimmed copy of the prebuilt libarduino_tinyusb.a.

The Arduino-ESP32 libs are built with every TinyUSB class enabled. usbd.c's and
usbh.c's driver tables reference all of them, so a USB-MSC-only firmware still
links the UAC2 audio, NCM, DFU, video, MIDI, vendor, HID and CDC device drivers
and the whole host stack (~49 KB of internal .bss on the ESP32-S31).

This copies the archive into the build dir, deletes the class/host objects that
CrossPoint never uses, and adds stubs for the driver-table entries the remaining
objects still reference: open() returns 0, so no stubbed class ever claims an
interface. Every other symbol stays as prebuilt. A firmware that does call one
of the removed APIs fails to link instead of silently getting a stub.
"""

import re
import subprocess
from pathlib import Path

Import("env")  # noqa: F821

# Objects to drop. Kept: tusb, tusb_fifo, usbd, dcd_dwc2, dwc2_common, msc_device.
REMOVE = [
    "audio_device.c.obj",
    "video_device.c.obj",
    "dfu_device.c.obj",
    "dfu_rt_device.c.obj",
    "vendor_device.c.obj",
    "ncm_device.c.obj",
    "ecm_rndis_device.c.obj",
    "usbtmc_device.c.obj",
    "midi_device.c.obj",
    "hid_device.c.obj",
    "cdc_device.c.obj",
    "usbh.c.obj",
    "hub.c.obj",
    "cdc_host.c.obj",
    "hid_host.c.obj",
    "midi_host.c.obj",
    "msc_host.c.obj",
    "hcd_dwc2.c.obj",
]

# Stubs returning true: deinit (nothing to tear down). Everything else returns
# 0/false (open claims nothing, xfer/control callbacks report "not handled",
# tuh_inited/tuh_rhport_init report no host stack).
RETURN_TRUE = re.compile(r"_deinit$")


def _tool(name):
    cc = env.WhereIs(env.subst("$CC")) or env.subst("$CC")  # noqa: F821
    return str(Path(cc).with_name(Path(cc).name.replace("gcc", name)))


def _run(args, **kw):
    return subprocess.run(args, check=True, capture_output=True, text=True, env=env["ENV"], **kw).stdout  # noqa: F821


def _symbols(nm, archive):
    """{object: (defined{name: type}, undefined set)} for every member."""
    out = {}
    current = None
    for line in _run([nm, "-A", archive]).splitlines():
        # path/lib.a:member.o:00000000 T name   or   path/lib.a:member.o:         U name
        head, _, rest = line.rpartition(":")
        member = head.rsplit(":", 1)[-1] if ":" in head else head
        parts = rest.split()
        if len(parts) == 3:
            _, typ, name = parts
        elif len(parts) == 2:
            typ, name = parts
        else:
            continue
        defined, undefined = out.setdefault(member, ({}, set()))
        if typ == "U":
            undefined.add(name)
        elif typ.isupper():
            defined[name] = typ
    return out


def build_trimmed():
    prebuilt = None
    for d in env["LIBPATH"]:  # noqa: F821
        p = Path(env.subst(str(d))) / "libarduino_tinyusb.a"  # noqa: F821
        if p.is_file():
            prebuilt = p
            break
    if prebuilt is None:
        print("trim_tinyusb: libarduino_tinyusb.a not found; linking the prebuilt libs unchanged")
        return

    out_dir = Path(env.subst("$BUILD_DIR")) / "tusb_trim"  # noqa: F821
    out_dir.mkdir(parents=True, exist_ok=True)
    trimmed = out_dir / "libarduino_tinyusb.a"
    stamp = out_dir / "source.txt"
    key = f"{prebuilt} {prebuilt.stat().st_size} {prebuilt.stat().st_mtime_ns}"
    if trimmed.is_file() and stamp.is_file() and stamp.read_text() == key:
        env.Prepend(LIBPATH=[str(out_dir)])  # noqa: F821
        return

    nm, ar = _tool("nm"), _tool("ar")
    syms = _symbols(nm, str(prebuilt))
    removed_defs = {}
    for obj in REMOVE:
        if obj in syms:
            removed_defs.update(syms[obj][0])
    kept_undef = set()
    for obj, (_, undef) in syms.items():
        if obj not in REMOVE:
            kept_undef |= undef
    needed = sorted(kept_undef & removed_defs.keys())
    data = [n for n in needed if removed_defs[n] != "T"]
    if data:
        raise SystemExit(f"trim_tinyusb: kept objects reference removed data symbols: {data}")

    stub_c = out_dir / "tusb_trim_stubs.c"
    lines = ["// Generated by scripts/trim_tinyusb.py: driver-table stubs for removed TinyUSB classes."]
    for name in needed:
        lines.append(f"int {name}(void) {{ return {1 if RETURN_TRUE.search(name) else 0}; }}")
    stub_c.write_text("\n".join(lines) + "\n")

    all_flags = env.subst("$CCFLAGS $CFLAGS $ASFLAGS $LINKFLAGS").split()  # noqa: F821
    flags = list(dict.fromkeys(f for f in all_flags if f.startswith(("-march=", "-mabi=", "-mno-cm"))))
    if not any(f.startswith("-march=") for f in flags):
        raise SystemExit("trim_tinyusb: no -march in the build flags; refusing to build an ABI-mismatched stub")
    stub_o = out_dir / "tusb_trim_stubs.c.obj"
    _run([env.WhereIs(env.subst("$CC")) or env.subst("$CC"), *flags, "-Os", "-ffunction-sections",  # noqa: F821
          "-c", str(stub_c), "-o", str(stub_o)])

    if trimmed.exists():
        trimmed.unlink()
    trimmed.write_bytes(prebuilt.read_bytes())
    present = [o for o in REMOVE if o in syms]
    _run([ar, "d", str(trimmed), *present])
    _run([ar, "rs", str(trimmed), str(stub_o)])
    stamp.write_text(key)
    print(f"trim_tinyusb: removed {len(present)} objects, stubbed {len(needed)} symbols -> {trimmed}")
    env.Prepend(LIBPATH=[str(out_dir)])  # noqa: F821


build_trimmed()
