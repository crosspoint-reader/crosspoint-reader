"""Generate fixed receiver replies; run with --check to detect stale output."""
from pathlib import Path
import argparse
import plistlib

ROOT = Path(__file__).resolve().parents[1] if "__file__" in globals() else Path.cwd()
OUTPUT = ROOT / 'vendor/esp32drop/src/airdrop/core/ad_identity.h'


def generate():
    lines = ['// Generated by scripts/generate_airdrop_identity.py; do not edit.',
             '#pragma once', '#include <stdint.h>', '']
    for condition, name in [('#if FREEINK_DEVICE_X4CLASSIC', 'CrossPoint X4C'),
                            ('#else', 'CrossPoint X4 Pro')]:
        lines += [condition, f'static const char AD_RECEIVER_NAME[] = "{name}";']
        for symbol, discover in [('AD_DISC_BODY', True), ('AD_ASK_BODY', False)]:
            value = {'ReceiverComputerName': name, 'ReceiverModelName': 'M5Stack'}
            if discover:
                value['ReceiverMediaCapabilities'] = b'{"Version":1}'
            data = plistlib.dumps(value, fmt=plistlib.FMT_BINARY, sort_keys=True)
            lines.append(f'static const uint8_t {symbol}[] = {{')
            for start in range(0, len(data), 16):
                lines.append('  ' + ', '.join(f'0x{b:02x}' for b in data[start:start+16]) + ',')
            lines.append('};')
    return '\n'.join(lines + ['#endif', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit('AirDrop identity header is stale')
    elif not OUTPUT.exists() or OUTPUT.read_text() != generated:
        OUTPUT.write_text(generated)

if "Import" in globals():
    generated = generate()
    if not OUTPUT.exists() or OUTPUT.read_text() != generated:
        OUTPUT.write_text(generated)
