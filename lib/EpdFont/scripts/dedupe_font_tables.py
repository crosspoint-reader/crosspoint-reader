#!/usr/bin/env python3
"""Share identical built-in lookup tables after font conversion."""

import argparse
import hashlib
import re
from collections import defaultdict
from pathlib import Path


ARRAY = re.compile(
    r"static const (EpdUnicodeInterval|EpdLigaturePair|uint16_t|uint8_t|int8_t) "
    r"(\w+)\[\]\s*=\s*\{(.*?)\};\n?", re.DOTALL
)
SHARED_HEADER = "SharedFontTables.h"
SHARED_INCLUDE = f'#include "{SHARED_HEADER}"\n'


def dedupe(font_dir):
    paths = sorted(font_dir.glob("*.h"))
    sources = {p: p.read_text() for p in paths}
    tables = defaultdict(list)
    for path, source in sources.items():
        for match in ARRAY.finditer(source):
            kind, name, body = match.groups()
            if path.name == SHARED_HEADER and not any(
                re.search(rf"\b{name}\b", text)
                for other, text in sources.items() if other != path
            ):
                continue
            if path.name != SHARED_HEADER and not any(
                part in name for part in ("Intervals", "Kern", "LigaturePairs")
            ):
                continue
            tokens = re.sub(r"//[^\n]*", "", body)
            key = kind, re.sub(r"\s+", "", tokens)
            tables[key].append((path, match))

    replacements = {}
    removals = set()
    shared = []
    for (kind, tokens), entries in tables.items():
        # Keep existing shared definitions when rerunning after a partial conversion.
        if len(entries) < 2 and entries[0][0].name != SHARED_HEADER:
            continue
        digest = hashlib.sha256(f"{kind}:{tokens}".encode()).hexdigest()[:16]
        name = f"builtinFontTable_{digest}"
        body = entries[0][1].group(3)
        shared.append((name, f"static const {kind} {name}[] = {{{body}}};\n"))
        for path, match in entries:
            replacements[match.group(2)] = name
            removals.add((path, match.start()))

    for path, source in sources.items():
        if path.name == SHARED_HEADER:
            continue
        source = ARRAY.sub(
            lambda m: "" if (path, m.start()) in removals else m.group(0), source
        )
        source = re.sub(r"\b\w+\b", lambda m: replacements.get(m.group(), m.group()), source)
        if "builtinFontTable_" in source and SHARED_INCLUDE not in source:
            source = source.replace('#include "EpdFontData.h"\n',
                                    '#include "EpdFontData.h"\n' + SHARED_INCLUDE)
        path.write_text(source)

    (font_dir / SHARED_HEADER).write_text(
        '// Generated by dedupe_font_tables.py.\n#pragma once\n#include "EpdFontData.h"\n\n'
        + "\n".join(definition for _, definition in sorted(shared))
    )
    print(f"Shared {len(shared)} font lookup tables")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font_dir", type=Path)
    dedupe(parser.parse_args().font_dir)
