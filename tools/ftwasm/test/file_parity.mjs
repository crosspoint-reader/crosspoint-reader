#!/usr/bin/env node
// Whole-file parity: fontconvert_sdcard.py CLI vs cpfont-writer.mjs, byte for byte.
//
//   node test/file_parity.mjs [--cases Literata,Bookerly,...] [--regen] [--dist <dir>]
//   node test/file_parity.mjs --kerning first-match --script <patched fontconvert_sdcard.py>
//
// --kerning first-match checks the opt-in kerning fix against a copy of the
// script with kerning-first-match.patch applied (cached in out/cli-first-match/); patch: patches/fontconvert_sdcard-kerning-first-match.patch.
//
// The Python side is invoked exactly like build-sd-fonts.py does it (multi-style
// flags, or positional font + --style for a single style; --intervals --sizes
// --name --output-dir), with the venv's freetype-py 2.5.1. Its files are cached
// in out/cli/<case>/ unless --regen.
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { FreeTypeWasm } from '../js/cpfont-raster.mjs';
import { convertFamily, FontError } from '../js/cpfont-writer.mjs';
import { findDist, REPO } from './jobs.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const D = path.join(REPO, 'lib/EpdFont/scripts/downloaded_fonts');
const B = path.join(REPO, 'lib/EpdFont/builtinFonts/source');
const LGC = 'builtin,latin-cyrillic,greek-letters,musical-symbols';

const CASES = [
  { id: 'Literata', what: 'sd-fonts.yaml family, GPOS extension lookups', name: 'Literata', intervals: LGC,
    sizes: '10,12,14,16,18', styles: {
      regular: `${D}/Literata/Literata-Regular.ttf`, bold: `${D}/Literata/Literata-Bold.ttf`,
      italic: `${D}/Literata/Literata-Italic.ttf`, bolditalic: `${D}/Literata/Literata-BoldItalic.ttf` } },
  { id: 'Bookerly', what: 'GPOS + GSUB extension lookups (ligatures via type 7), as generate-sd-fonts.sh',
    name: 'Bookerly-SD', intervals: 'builtin', sizes: '12,14,16,18', styles: {
      regular: `${B}/Bookerly/Bookerly-Regular.ttf`, bold: `${B}/Bookerly/Bookerly-Bold.ttf`,
      italic: `${B}/Bookerly/Bookerly-Italic.ttf`, bolditalic: `${B}/Bookerly/Bookerly-BoldItalic.ttf` } },
  { id: 'OpenDyslexic', what: 'CFF outlines (repo)', name: 'OpenDyslexic', intervals: LGC, sizes: '12,16', styles: {
      regular: `${B}/OpenDyslexic/OpenDyslexic-Regular.otf`, bold: `${B}/OpenDyslexic/OpenDyslexic-Bold.otf`,
      italic: `${B}/OpenDyslexic/OpenDyslexic-Italic.otf`, bolditalic: `${B}/OpenDyslexic/OpenDyslexic-BoldItalic.otf` } },
  { id: 'SourceSerif4Otf', what: 'CFF outlines (Adobe release, downloaded)', name: 'SourceSerif4', intervals: LGC,
    sizes: '14', styles: {
      regular: `${ROOT}/dl/fonts-otf/SourceSerif4-Regular.otf`, italic: `${ROOT}/dl/fonts-otf/SourceSerif4-It.otf` } },
  { id: 'Inter', what: '2048 upem: exact .5 kerning values at 12 pt (round-half-even)', name: 'Inter', intervals: LGC,
    sizes: '12,14', styles: { regular: `${B}/Inter/Inter-Regular.ttf`, bold: `${B}/Inter/Inter-Bold.ttf` } },
  { id: 'KernTest', what: "legacy 'kern' table: + GPOS, multi-subtable, Apple v1 (generated by make_kern_fonts.py)",
    name: 'KernTest', intervals: LGC, sizes: '12,14', styles: {
      regular: `${ROOT}/out/fonts-kern/KernTest-Regular.ttf`, italic: `${ROOT}/out/fonts-kern/KernTest-Italic.ttf`,
      bolditalic: `${ROOT}/out/fonts-kern/KernTest-BoldItalic.ttf` } },
  { id: 'SyntheticBold', what: '--synthetic-bold (bold = regular file)', name: 'SynthBold', intervals: 'builtin',
    sizes: '14', syntheticBold: true, styles: {
      regular: `${D}/Literata/Literata-Regular.ttf`, bold: `${D}/Literata/Literata-Regular.ttf`,
      italic: `${D}/Literata/Literata-Italic.ttf`, bolditalic: `${D}/Literata/Literata-Italic.ttf` } },
  { id: 'Single', what: 'single-style mode (positional font + --style)', name: 'Charis', intervals: LGC, sizes: '14',
    styles: { regular: `${D}/Charis/NV_Charis-Regular.ttf` } },
];

function parseArgs(argv) {
  const a = { cases: CASES.map((c) => c.id).join(','), regen: false, python: 'venv/bin/python', dist: '',
              kerning: 'sum', script: path.join(REPO, 'lib/EpdFont/scripts/fontconvert_sdcard.py') };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i].replace(/^--/, '');
    if (k === 'regen') a.regen = true;
    else a[k] = argv[++i];
  }
  if (!path.isAbsolute(a.python)) a.python = path.join(ROOT, a.python);
  return a;
}

function runPython(args, c, outDir) {
  const expected = c.sizes.split(',').map((s) => path.join(outDir, `${c.name}_${s.trim()}.cpfont`));
  if (!args.regen && expected.every((f) => fs.existsSync(f))) return null;
  fs.rmSync(outDir, { recursive: true, force: true });
  const styleNames = Object.keys(c.styles);
  const cmd = ['-I', '-B', path.resolve(ROOT, args.script)];
  if (styleNames.length > 1) for (const s of styleNames) cmd.push(`--${s}`, c.styles[s]);
  else cmd.push(c.styles[styleNames[0]], '--style', styleNames[0]);
  cmd.push('--intervals', c.intervals, '--sizes', c.sizes, '--name', c.name, '--output-dir', `${outDir}/`);
  if (c.syntheticBold) cmd.push('--synthetic-bold');
  const t = performance.now();
  const r = spawnSync(args.python, cmd, { encoding: 'utf8' });
  if (r.status !== 0) throw new Error(`fontconvert_sdcard.py failed for ${c.id}:\n${r.stderr}`);
  const seconds = (performance.now() - t) / 1000;
  fs.writeFileSync(path.join(outDir, 'python-seconds.txt'), `${seconds}\n`);
  return seconds;
}

/** Name the section a byte offset falls into, from the reference file's own header/TOC. */
function locate(buf, off) {
  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);
  const n = dv.getUint8(12);
  if (off < 32) return 'header';
  if (off < 32 + 32 * n) return `TOC entry ${Math.floor((off - 32) / 32)} byte ${(off - 32) % 32}`;
  const styles = [];
  for (let i = 0; i < n; i++) {
    const t = 32 + 32 * i;
    styles.push({ id: dv.getUint8(t), intervals: dv.getUint32(t + 4, true), glyphs: dv.getUint32(t + 8, true),
                  kl: dv.getUint16(t + 17, true), kr: dv.getUint16(t + 19, true), lc: dv.getUint8(t + 21),
                  rc: dv.getUint8(t + 22), lig: dv.getUint8(t + 23), data: dv.getUint32(t + 24, true) });
  }
  for (let i = n - 1; i >= 0; i--) {
    const s = styles[i];
    if (off < s.data) continue;
    let p = s.data;
    const secs = [['intervals', s.intervals * 12, 12], ['glyphs', s.glyphs * 16, 16], ['kern left', s.kl * 3, 3],
                  ['kern right', s.kr * 3, 3], ['kern matrix', s.lc * s.rc, s.rc || 1], ['ligatures', s.lig * 8, 8],
                  ['bitmaps', Infinity, 1]];
    for (const [name, len, rec] of secs) {
      if (off < p + len) return `style ${s.id} ${name} [${Math.floor((off - p) / rec)}] +${(off - p) % rec}`;
      p += len;
    }
  }
  return '?';
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const dist = findDist(ROOT, args.dist);
  const { default: createFtWasm } = await import(pathToFileURL(path.join(dist, 'ftwasm.mjs')).href);
  const ft = await FreeTypeWasm.create(createFtWasm);
  const v = ft.version();
  console.log(`wasm: ${path.relative(ROOT, dist) || '.'} (FreeType ${v.string}${v.harfbuzz ? ' + HarfBuzz' : ''}), ` +
              `kerning ${args.kerning}, python script ${args.script}\n`);

  let files = 0, identical = 0, bytes = 0;
  const wanted = new Set(args.cases.split(','));
  for (const c of CASES.filter((x) => wanted.has(x.id))) {
    if (c.id === 'KernTest' && !fs.existsSync(c.styles.regular)) {
      const r = spawnSync(args.python, ['-I', '-B', path.join(ROOT, 'test/make_kern_fonts.py'),
                                        `${B}/Inter/Inter-Regular.ttf`, path.dirname(c.styles.regular)], { encoding: 'utf8' });
      if (r.status !== 0) throw new Error(`make_kern_fonts.py failed:\n${r.stderr}`);
    }
    const missing = Object.values(c.styles).filter((f) => !fs.existsSync(f));
    if (missing.length) {
      console.log(`${c.id.padEnd(16)} skipped: missing ${missing.join(', ')}` +
                  (c.id === 'SourceSerif4Otf' ? ' (from https://github.com/adobe-fonts/source-serif/tree/release/OTF)' : ''));
      continue;
    }
    const outDir = path.join(ROOT, args.kerning === 'sum' ? 'out/cli' : `out/cli-${args.kerning}`, c.id);
    runPython(args, c, outDir);
    const pySec = Number(fs.readFileSync(path.join(outDir, 'python-seconds.txt'), 'utf8'));
    const fonts = {}, fileNames = {};
    for (const [s, f] of Object.entries(c.styles)) { fonts[s] = new Uint8Array(fs.readFileSync(f)); fileNames[s] = path.basename(f); }
    const t = performance.now();
    const out = convertFamily(ft, { fonts, fileNames, sizes: c.sizes, intervals: c.intervals, name: c.name,
                                    syntheticBold: !!c.syntheticBold, kerning: args.kerning });
    const ms = performance.now() - t;
    const notes = [];
    let ok = 0;
    for (const f of out) {
      const ref = new Uint8Array(fs.readFileSync(path.join(outDir, f.fileName)));
      files++;
      bytes += ref.length;
      let diff = -1;
      const n = Math.min(ref.length, f.bytes.length);
      for (let i = 0; i < n; i++) if (ref[i] !== f.bytes[i]) { diff = i; break; }
      if (diff < 0 && ref.length !== f.bytes.length) diff = n;
      if (diff < 0) { ok++; identical++; continue; }
      notes.push(`${f.fileName}: first difference at byte ${diff} (${locate(ref, diff)}), sizes ${ref.length} vs ${f.bytes.length}`);
    }
    const st = out[0].styles.map((s) => `${s.style[0]}${s.style.includes('italic') && s.style !== 'italic' ? 'i' : ''}` +
      `:${s.kernLeftClasses}x${s.kernRightClasses}k/${s.ligatures}l`).join(' ');
    console.log(`${c.id.padEnd(16)} ${ok}/${out.length} files identical  ` +
                `js ${(ms / 1000).toFixed(2).padStart(5)} s  python ${pySec.toFixed(1).padStart(5)} s  ` +
                `[${st} @${out[0].size}pt]  ${c.what}`);
    for (const n of notes) console.log(`    ${n}`);
  }

  // Variable fonts are refused with a clear error (the Python script would silently use the default instance).
  let refusal = 'NOT refused';
  try {
    convertFamily(ft, { fonts: { regular: new Uint8Array(fs.readFileSync(`${D}/Bitter/Bitter%5Bwght%5D.ttf`)) },
                        fileNames: { regular: 'Bitter[wght].ttf' }, sizes: [14], intervals: 'ascii', name: 'Bitter' });
  } catch (e) {
    refusal = e instanceof FontError ? `refused: ${e.message}` : `unexpected error: ${e.message}`;
  }
  console.log(`\nvariable font: ${refusal}`);
  console.log(`\nTOTAL ${identical}/${files} files byte-identical (${(bytes / 1048576).toFixed(1)} MB compared)`);
  process.exitCode = identical === files && refusal.startsWith('refused') ? 0 : 1;
}

main().catch((e) => { console.error(e); process.exit(2); });
